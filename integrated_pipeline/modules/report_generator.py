from __future__ import annotations

from datetime import datetime, timezone
from io import BytesIO
import json
import textwrap
from typing import Any

import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages
import numpy as np


DISCLAIMER = (
    "Research decision-support prototype only. Not a diagnosis or treatment recommendation. "
    "All outputs require review by qualified clinicians."
)


def generate_markdown_report(result: dict[str, Any]) -> str:
    input_info = result.get("input", {})
    segmentation = result.get("segmentation", {})
    classification = result.get("classification", {})
    explainability = result.get("explainability", {})
    spatial = result.get("spatial_risk", {})
    corridors = result.get("surgical_corridors", {})
    segmentation3d = result.get("segmentation3d_metadata", {})
    volume_stage = result.get("stages", {}).get("3D segmentation", {})
    rag = result.get("rag")
    statuses = result.get("stages", {})
    risk_stage = statuses.get(
        "surgical risk mapping", statuses.get("Spatial risk mapping", {})
    )
    corridor_stage = statuses.get("Surgical corridors", {})
    risk_result = result.get("risk_mapping")

    lines = [
        "# Brain MRI Analysis Report",
        "",
        "### Input Summary",
        "",
        f"- Input identifier: {result.get('case_id', 'not provided')}",
        f"- Available modality: {input_info.get('modality', 'not provided')}",
        f"- Study modalities: {', '.join(input_info.get('modalities', [])) or 'not available'}",
        (
            "- SynthSeg labels: supplied but not validated or used"
            if result.get("synthseg_supplied")
            else "- SynthSeg labels: not supplied"
        ),
        f"- Image dimensions: {input_info.get('shape', 'not available')}",
        f"- Original dimensions: {input_info.get('original_shape', 'not applicable')}",
        f"- Orientation: {input_info.get('orientation', 'not applicable')}",
        f"- Voxel spacing (mm): {input_info.get('voxel_spacing_mm', 'not available')}",
        f"- Preprocessing status: {input_info.get('preprocessing_status', 'not run')}",
        f"- Selected slice: {input_info.get('slice_index', 'not applicable')}",
        "",
        "### Segmentation Findings",
        "",
        f"- Status: {segmentation.get('status', 'not run')}",
        f"- Selected model: {segmentation.get('architecture', 'not available')}",
        f"- Checkpoint: {segmentation.get('checkpoint', 'not available')}",
        f"- Checkpoint integrity: {segmentation.get('checkpoint_integrity', 'not verified')}",
        f"- Segmentation classes: {segmentation.get('classes', 'not available')}",
        f"- Foreground area: {segmentation.get('foreground_area', 'not available')}",
        f"- Inference time (seconds): {segmentation.get('inference_time_seconds', 'not available')}",
        f"- Limitation: {segmentation.get('limitation', 'No model output was produced.')}",
        "",
        "### 3D Segmentation",
        "",
        f"- Status: {volume_stage.get('status', 'not run')}",
        f"- Pipeline: {result.get('model_3d', 'not run')}",
        f"- Output order: {segmentation3d.get('region_order', 'not available')}",
        f"- Threshold: {segmentation3d.get('inference', {}).get('threshold', 'not available')}",
        f"- Mask voxel counts: {segmentation3d.get('mask_voxel_count', 'not available')}",
        "- RC: unavailable; not documented or generated by this checkpoint.",
        "- Clinical performance: unvalidated.",
        "",
        "### Classification Findings",
        "",
        f"- Status: {classification.get('status', 'not run')}",
        f"- Predicted class: {classification.get('predicted_class', 'not available')}",
        f"- Raw scores: {classification.get('scores', 'not available')}",
        f"- Uncalibrated softmax output: {classification.get('probabilities', 'not available')}",
        f"- Model identity: {classification.get('architecture', 'not available')}",
        f"- Checkpoint: {classification.get('checkpoint', 'not available')}",
        f"- Checkpoint integrity: {classification.get('checkpoint_integrity', 'not verified')}",
        f"- Inference time (seconds): {classification.get('inference_time_seconds', 'not available')}",
        f"- Limitation: {classification.get('limitation', 'No model output was produced.')}",
        "",
        "### Explainability",
        "",
        f"- Status: {explainability.get('status', 'not run')}",
        f"- Method and target: {explainability.get('method', 'not available')}",
        f"- Observation: {explainability.get('observation', 'No heatmap was generated.')}",
        "- Interpretation: Heatmaps show model-relevant image regions and do not establish diagnostic correctness.",
        "",
        "### Spatial Risk Assessment",
        "",
        f"- Status: {risk_stage.get('status', spatial.get('status', 'not run'))}",
        f"- Available result: {risk_result.get('active_weights', 'not available') if isinstance(risk_result, dict) else 'not available'}",
        f"- Missing data: {'; '.join(risk_stage.get('reasons', [])) or spatial.get('missing_data', 'No missing prerequisites reported.')}",
        "- Research risk scores are not calibrated probabilities of surgical injury.",
        "",
        "### Surgical Corridor Analysis",
        "",
        f"- Status: {corridor_stage.get('status', corridors.get('status', 'not run'))}",
    ]
    corridor_records = (
        risk_result.get("corridors", []) if isinstance(risk_result, dict) else []
    )
    if corridor_records:
        lines.extend(
            [
                "",
                "| Candidate corridor | Length (mm) | Mean risk | Maximum risk | Tract risk | Tumor coverage | Composite cost |",
                "|---|---:|---:|---:|---:|---:|---:|",
            ]
        )
        for corridor in corridor_records:
            lines.append(
                "| "
                + " | ".join(
                    str(value if value is not None else "not available").replace("|", "\\|")
                    for value in (
                        corridor.get("corridor_name", corridor.get("corridor_id", "not available")),
                        corridor.get("path_length_mm", corridor.get("length_mm")),
                        corridor.get("mean_risk"),
                        corridor.get("maximum_risk", corridor.get("max_risk")),
                        corridor.get("tract_risk"),
                        corridor.get("tumor_coverage", corridor.get("coverage")),
                        corridor.get("composite_cost"),
                    )
                )
                + " |"
            )
    else:
        lines.append("- Candidate corridor results: not available.")
    lines.extend(
        [
            f"- Missing prerequisites: {'; '.join(corridor_stage.get('reasons', [])) or corridors.get('missing_data', 'No missing prerequisites reported.')}",
            "",
            "### Evidence Summary",
            "",
        ]
    )
    if rag and rag.get("status") == "failed":
        lines.extend(
            [
                "- Retrieval status: failed",
                f"- Failure: {rag.get('reason', 'RAG request failed.')}",
            ]
        )
    elif rag:
        answer = rag.get("answer", {})
        lines.extend(
            [
                f"- Retrieval status: {rag.get('evidence_status', 'not verified')}",
                f"- Summary: {answer.get('summary', 'No summary returned.')}",
                f"- Retrieved citations: {rag.get('citations', [])}",
            ]
        )
    else:
        lines.append("- RAG: not run; no literature evidence is included.")
    lines.extend(["", "### Findings Summary", ""])
    lines.extend(_findings_summary(result))
    lines.extend(["", "### Overall Summary", ""])
    completed = [
        name for name, stage in statuses.items() if stage.get("status") == "completed"
    ]
    lines.append(
        "Completed stages: " + (", ".join(completed) if completed else "none.")
    )
    lines.extend(["", "### Limitations", ""])
    if statuses:
        for name, stage in statuses.items():
            if stage.get("status") != "completed":
                reasons = "; ".join(stage.get("reasons", []))
                lines.append(
                    f"- {name}: {stage.get('status', 'not run')}"
                    + (f" — {reasons}" if reasons else "")
                )
    else:
        lines.append("- No analysis stages have been run.")
    lines.extend(["", DISCLAIMER, ""])
    return "\n".join(lines)


def generate_pdf_report(result: dict[str, Any]) -> bytes:
    buffer = BytesIO()
    with PdfPages(buffer) as pdf:
        _add_text_pages(
            pdf,
            "Brain MRI Analysis Report",
            generate_markdown_report(result).splitlines(),
        )
    return buffer.getvalue()


def generate_report(result: dict[str, Any]) -> bytes:
    """Create a PDF exclusively from structured results actually provided."""
    buffer = BytesIO()
    with PdfPages(buffer) as pdf:
        lines = [
            f"Generated (UTC): {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
            "Project: Brain Tumor Analysis",
            f"Study: {result.get('case_id', 'not provided')}",
            "Ground truth: not supplied; all segmentation masks are model predictions.",
            "",
            "Findings summary:",
            *_findings_summary(result),
            "",
            f"3D model: {result.get('model_3d', 'not run')}",
            f"2D segmentation model: {result.get('model_2d_segmentation', 'not run')}",
            f"2D classification model: {result.get('model_2d_classification', 'not run')}",
            f"Input dimensions: {result.get('input_shape', 'not available')}",
            f"Model-space dimensions: {result.get('output_shape', 'not available')}",
            f"Model-space orientation: {result.get('orientation', 'not available')}",
            f"Model-space voxel spacing (mm): {result.get('output_spacing_mm', 'not available')}",
            f"Input voxel-to-world affine: {result.get('input_affine', 'not available')}",
            f"Model-space voxel-to-world affine: {result.get('output_affine', 'not available')}",
            f"Selected axial slice index: {result.get('slice_index', 'not available')}",
            f"Inference device: {result.get('inference_device', 'not recorded')}",
            f"Software versions: {result.get('software_versions', {})}",
            f"Seed: {result.get('seed', 'not recorded')}",
            f"3D prediction threshold: {result.get('prediction_threshold', 'not recorded')}",
            f"3D region definitions: {result.get('region_definitions', {})}",
            (
                "3D segmentation metadata: "
                + json.dumps(
                    result.get("segmentation3d_metadata", {}),
                    sort_keys=True,
                    default=str,
                )
            ),
            (
                "SynthSeg labels were supplied but not validated or used."
                if result.get("synthseg_supplied")
                else (
                    "SynthSeg provenance: user-supplied; label provenance is not independently verified."
                    if result.get("stages", {})
                    .get("surgical risk mapping", {})
                    .get("status")
                    in {"completed", "failed"}
                    else "SynthSeg labels not supplied; V8 risk mapping was not run."
                )
            ),
            f"Input modalities: {', '.join(result.get('modalities', []))}",
            "Resolved 3D configuration: "
            + json.dumps(result.get("model_configuration", {}), sort_keys=True, default=str),
            "",
            "Stages:",
        ]
        for name, stage in result.get("stages", {}).items():
            lines.append(f"- {name}: {stage.get('status', 'not run')}")
            for reason in stage.get("reasons", []):
                lines.append(f"    {reason}")
            if stage.get("note"):
                lines.append(f"    Note: {stage['note']}")
        classification = result.get("classification")
        if isinstance(classification, dict) and classification.get("predicted_class"):
            lines.extend(
                [
                    "",
                    "Classification model output (not a diagnosis):",
                    f"Predicted class: {classification.get('predicted_class')}",
                    f"Class probabilities (model output): {classification.get('probabilities', 'not available')}",
                ]
            )
        segmentation_metadata = result.get("segmentation2d_metadata")
        if segmentation_metadata:
            lines.extend(
                [
                    "",
                    "2D segmentation configuration:",
                    json.dumps(segmentation_metadata, sort_keys=True, default=str),
                ]
            )
        risk = result.get("risk_mapping")
        if risk:
            lines.extend(
                [
                    "",
                    "V8 risk-map provenance (not clinical injury probabilities):",
                    risk.get("note", "Research-prototype score."),
                    f"Active component weights: {risk.get('active_weights', {})}",
                    f"Evidence availability: {risk.get('evidence_status', {})}",
                    "Spatial QC: "
                    + json.dumps(risk.get("qc", {}), sort_keys=True, default=str),
                    f"Component maps available: {list(risk.get('component_maps', {}))}",
                ]
            )
            for corridor in risk.get("corridors", []):
                lines.append(
                    "Corridor output: "
                    + json.dumps(corridor, sort_keys=True, default=str)
                )
        lines.extend(["", DISCLAIMER])
        _add_text_pages(pdf, "Brain Tumor Analysis - MRI Research Report", lines)

        visualization = result.get("segmentation_visualization")
        if isinstance(visualization, bytes):
            image = plt.imread(BytesIO(visualization), format="png")
            fig, ax = plt.subplots(figsize=(12, 4))
            ax.imshow(image)
            ax.set_title("3D Segmentation Visualization (TC / WT / ET)")
            ax.axis("off")
            pdf.savefig(fig, bbox_inches="tight")
            plt.close(fig)

        modality_slices = result.get("modality_slices")
        if isinstance(modality_slices, dict) and modality_slices:
            ordered_slices = [
                (name, np.asarray(image))
                for name, image in modality_slices.items()
                if image is not None
            ]
            if ordered_slices:
                fig, axes = plt.subplots(2, 2, figsize=(10, 9))
                for axis, (name, image) in zip(axes.flat, ordered_slices):
                    axis.imshow(image, cmap="gray")
                    axis.set_title(f"{name} axial slice {result.get('slice_index', 'n/a')}")
                    axis.axis("off")
                for axis in list(axes.flat)[len(ordered_slices) :]:
                    axis.axis("off")
                fig.suptitle("Co-registered MRI modality slices", fontsize=14)
                pdf.savefig(fig, bbox_inches="tight")
                plt.close(fig)

        if result.get("slice_image") is not None:
            image = np.asarray(result["slice_image"])
            fig, axes = plt.subplots(1, 2, figsize=(11, 5))
            axes[0].imshow(image, cmap="gray")
            region_masks = result.get("region_masks", {})
            if "WT" in region_masks:
                whole_tumor_slice = np.asarray(region_masks["WT"])[:, :, result["slice_index"]]
                axes[0].imshow(
                    np.ma.masked_where(whole_tumor_slice == 0, whole_tumor_slice),
                    cmap="autumn",
                    alpha=0.45,
                )
                axes[0].set_title(
                    f"3D WT model mask - axial RAS slice {result.get('slice_index')}"
                )
            else:
                axes[0].set_title("Selected 2D input; no 3D mask available")
            axes[0].axis("off")
            axes[1].imshow(image, cmap="gray")
            if result.get("segmentation2d") is not None:
                axes[1].imshow(
                    np.ma.masked_where(result["segmentation2d"] == 0, result["segmentation2d"]),
                    cmap="winter",
                    alpha=0.45,
                )
            axes[1].set_title("2D predicted mask overlay")
            axes[1].axis("off")
            pdf.savefig(fig, bbox_inches="tight")
            plt.close(fig)
            gradcam = result.get("gradcam")
            if isinstance(gradcam, dict) and gradcam.get("overlay") is not None:
                fig, ax = plt.subplots(figsize=(7, 7))
                ax.imshow(gradcam["overlay"])
                ax.set_title(
                    "Grad-CAM model-relevance overlay; not diagnostic evidence"
                )
                ax.axis("off")
                pdf.savefig(fig, bbox_inches="tight")
                plt.close(fig)
            if result.get("risk_mapping") is not None:
                risk_map = np.asarray(result["risk_mapping"]["risk_map"])
                fig, ax = plt.subplots(figsize=(7, 7))
                ax.imshow(image, cmap="gray")
                risk_slice = risk_map[:, :, result["slice_index"]]
                ax.imshow(
                    np.ma.masked_where(risk_slice <= 0, risk_slice),
                    cmap="turbo",
                    alpha=0.55,
                    vmin=0,
                    vmax=1,
                )
                corridor_mask = result["risk_mapping"].get("corridor_mask")
                if corridor_mask is not None:
                    corridor_slice = (
                        np.asarray(corridor_mask)[:, :, result["slice_index"]] > 0
                    ).astype(np.uint8)
                    if corridor_slice.any():
                        ax.contour(
                            corridor_slice,
                            levels=[0.5],
                            colors=["cyan"],
                            linewidths=0.6,
                        )
                ax.set_title("V8 normalized composite score and candidate corridors")
                ax.axis("off")
                pdf.savefig(fig, bbox_inches="tight")
                plt.close(fig)

        rag = result.get("rag")
        if rag:
            answer = rag.get("answer", {})
            paragraphs = [
                f"Context ID: {rag.get('queried_case_id', 'not provided')}",
                f"Question: {rag.get('query', 'not recorded')}",
                "Context: structured outputs from this run; raw uploaded MRI was not transmitted.",
                "Summary: " + str(answer.get("summary", "No summary returned.")),
            ]
            paragraphs.extend(
                f"Evidence-supported consideration: {item}"
                for item in answer.get("evidence_supported_considerations", [])
            )
            paragraphs.extend(f"Uncertainty: {item}" for item in answer.get("uncertainties", []))
            if rag.get("evidence_status") == "insufficient_evidence":
                paragraphs.append(str(rag.get("evidence_warning", "No evidence was retrieved.")))
            retrieved = rag.get("retrieved_evidence", [])
            for citation in rag.get("citations", []):
                source = next(
                    (
                        evidence
                        for evidence in retrieved
                        if isinstance(evidence, dict)
                        and (
                            (
                                citation.get("chunk_id")
                                and citation.get("chunk_id") == evidence.get("chunk_id")
                            )
                            or (
                                citation.get("paper_id")
                                and citation.get("paper_id") == evidence.get("paper_id")
                            )
                        )
                    ),
                    {},
                )
                metadata = source.get("metadata")
                if not isinstance(metadata, dict):
                    metadata = {}
                paragraphs.append(
                    "Citation: "
                    f"{citation.get('title') or source.get('title', 'Untitled')} "
                    f"({citation.get('paper_id') or source.get('paper_id', 'unknown')}); "
                    f"authors={metadata.get('authors', 'not provided')}; "
                    f"year={metadata.get('year', 'not provided')}; "
                    f"DOI={metadata.get('doi', 'not provided')}; "
                    f"citation_status={citation.get('status', 'not provided')}; "
                    f"URL={metadata.get('source_url', 'not provided')}"
                )
            paragraphs.extend(f"Warning: {warning}" for warning in rag.get("warnings", []))
            paragraphs.append(DISCLAIMER)
            _add_text_pages(pdf, "RAG Response and Retrieved Sources", paragraphs)
    return buffer.getvalue()


def _findings_summary(result: dict[str, Any]) -> list[str]:
    segmentation = result.get("segmentation", {})
    classification = result.get("classification", {})
    stages = result.get("stages", {})

    if segmentation.get("status") == "completed":
        segmentation_line = (
            "2D segmentation: model mask produced for the selected slice; "
            f"foreground {segmentation.get('foreground_area', 'not quantified')}. "
            "This is not a 3D tumor volume."
        )
    else:
        segmentation_line = (
            "2D segmentation: "
            f"{segmentation.get('status', 'not run')}; "
            f"{segmentation.get('limitation', 'no model output was produced')}."
        )

    if classification.get("status") == "completed":
        classification_line = (
            "2D classification: model output "
            f"{classification.get('predicted_class', 'not available')}; "
            "an uncalibrated BRISC image-folder class, not a diagnosis."
        )
    else:
        classification_line = (
            "2D classification: "
            f"{classification.get('status', 'not run')}; "
            f"{classification.get('limitation', 'no model output was produced')}."
        )

    volume_stage = stages.get("3D segmentation", {})
    risk_stage = stages.get(
        "Spatial risk mapping", stages.get("surgical risk mapping", {})
    )
    corridor_stage = stages.get("Surgical corridors", {})
    volume_metadata = result.get("segmentation3d_metadata", {})
    if volume_stage.get("status") == "completed":
        volume_summary = (
            "3D segmentation: completed model inference for the documented ET/TC/WT "
            f"channels; voxel counts {volume_metadata.get('mask_voxel_count', 'not recorded')}. "
            "RC is unavailable and clinical performance is unvalidated."
        )
    else:
        volume_summary = (
            "3D segmentation: "
            f"{volume_stage.get('status', 'not run')}; "
            "no 3D inference output was produced."
        )
    return [
        segmentation_line,
        classification_line,
        volume_summary,
        f"Spatial risk mapping: {risk_stage.get('status', 'not run')}.",
        f"Surgical corridor planning: {corridor_stage.get('status', 'not run')}.",
    ]


def _add_text_pages(pdf: PdfPages, title: str, paragraphs: list[str]) -> None:
    lines = [
        wrapped
        for paragraph in paragraphs
        for wrapped in (
            textwrap.wrap(
                str(paragraph), width=88, break_long_words=False, break_on_hyphens=False
            )
            or [""]
        )
    ]
    for start in range(0, max(1, len(lines)), 48):
        fig = plt.figure(figsize=(8.27, 11.69))
        fig.suptitle(title, fontsize=17, y=0.96)
        fig.text(
            0.08,
            0.9,
            "\n".join(lines[start : start + 48]),
            va="top",
            fontsize=9,
            family="monospace",
        )
        pdf.savefig(fig, bbox_inches="tight")
        plt.close(fig)
